// Uses an existing Playwright installation and Microsoft Edge; no project dependencies.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
(async () => {
  const browser = await chromium.launch({channel:'msedge',headless:true});
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1100},reducedMotion:'reduce'});
    const errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
    await page.goto(pathToFileURL(path.join(__dirname,'色彩实验室.html')).href);
    const screenshotDir=path.join(__dirname,'verification');
    await fs.mkdir(screenshotDir,{recursive:true});
    const count=n=>page.locator(`[data-count="${n}"]`).click();
    const slots=()=>page.locator('.custom-color b').allTextContents();
    const edit=async (i,hex)=>{
      await page.locator(`[data-custom-color="${i}"]`).click();
      await page.locator('#hex-input').fill(hex);
      await page.locator('#hex-input').press('Tab');
    };
    const gallery=()=>page.locator('.palette-strip').evaluateAll(strips=>strips.map(strip=>[...strip.querySelectorAll('[data-copy]')].map(b=>b.dataset.copy)));
    const checkGallery=async colors=>{
      const palettes=await gallery();
      assert.ok(palettes.length>=12);
      for(const p of palettes)assert.deepEqual([...p].sort(),[...colors].sort());
    };
    const noOverflow=async()=>assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Horizontal overflow');
    await page.locator('#help-button').click();
    assert.equal(await page.locator('#help-title').textContent(),'使用说明');
    const helpText=await page.locator('#help-dialog').textContent();
    for(const text of ['自主配色','交换顺序与保留颜色','隐藏栏位','Alt + ← / →','不会上传服务器或 GitHub'])assert.ok(helpText.includes(text));
    await page.screenshot({path:path.join(screenshotDir,'help-desktop.png')});
    await page.setViewportSize({width:390,height:1000});
    await noOverflow();
    assert.ok(await page.locator('#help-dialog').evaluate(dialog=>dialog.scrollWidth<=dialog.clientWidth),'Help dialog overflow');
    await page.screenshot({path:path.join(screenshotDir,'help-mobile.png')});
    await page.locator('.help-footnote').scrollIntoViewIfNeeded();
    assert.ok(await page.locator('.help-footnote').evaluate(el=>{const r=el.getBoundingClientRect();return r.top>=0 && r.bottom<=innerHeight;}));
    await page.keyboard.press('Escape');
    await page.setViewportSize({width:1440,height:1100});
    console.log('PASS help documents new features and fits desktop/mobile');
    const center=async i=>{
      await page.locator(`[data-custom-color="${i}"]`).scrollIntoViewIfNeeded();
      const r=await page.locator(`[data-custom-color="${i}"]`).boundingBox();
      return {x:r.x+r.width/2,y:r.y+r.height/2};
    };
    const drag=async(from,to)=>{
      const a=await center(from),b=await center(to);
      await page.mouse.move(a.x,a.y);await page.mouse.down();
      await page.mouse.move(b.x,b.y,{steps:8});await page.mouse.up();
    };
    const exploreBase=await page.locator('#hex-input').inputValue();
    await page.locator('[data-page="custom"]').click();
    assert.ok(await page.locator('.relationship-title').isVisible());
    assert.ok(await page.locator('.relation-tabs').isVisible());
    await count(4);
    const four=['#123456','#ABCDEF','#E13278','#09BC76'];
    for(let i=0;i<four.length;i++)await edit(i,four[i]);
    await count(2);
    await checkGallery(four.slice(0,2));
    await count(4);
    assert.deepEqual(await slots(),four);
    await checkGallery(four);
    console.log('PASS four → two → four retains edited colors');
    await page.locator('[data-custom-color="3"]').click();
    const beforeSwap=await gallery();
    const previewColors=()=>page.locator('.card-art .preview').evaluateAll(previews=>previews.map(preview=>Array.from({length:5},(_,i)=>preview.style.getPropertyValue(`--p${i}`))));
    const beforePreview=await previewColors();
    await drag(0,3);
    const reordered=[four[3],four[1],four[2],four[0]];
    assert.deepEqual(await slots(),reordered);
    assert.equal(await page.locator('#hex-input').inputValue(),four[3]);
    assert.equal(await page.locator('[data-custom-color="0"]').getAttribute('aria-pressed'),'true');
    assert.deepEqual(await gallery(),beforeSwap.map(p=>p.map(hex=>hex===four[0]?four[3]:hex===four[3]?four[0]:hex)));
    assert.deepEqual(await previewColors(),beforePreview.map(p=>p.map(hex=>hex===four[0]?four[3]:hex===four[3]?four[0]:hex)));
    await page.screenshot({path:path.join(screenshotDir,'custom-reordered.png')});
    await count(2);await checkGallery(reordered.slice(0,2));
    await count(4);assert.deepEqual(await slots(),reordered);
    await page.reload();await page.locator('[data-page="custom"]').click();
    assert.deepEqual(await slots(),reordered);
    console.log('PASS drag swaps previews, keeps editing selection, controls retained colors and survives reload');
    const a=await center(0),b=await center(2);
    await page.mouse.move(a.x,a.y);await page.mouse.down();await page.mouse.move(b.x,b.y,{steps:5});
    await page.keyboard.press('Escape');await page.mouse.up();
    assert.deepEqual(await slots(),reordered);
    await page.mouse.move(a.x,a.y);await page.mouse.down();await page.mouse.move(5,5,{steps:5});await page.mouse.up();
    assert.deepEqual(await slots(),reordered);
    await page.locator('[data-custom-color="1"]').click();
    assert.equal(await page.locator('#hex-input').inputValue(),reordered[1]);
    await page.locator('[data-custom-color="1"]').press('Alt+ArrowRight');
    assert.deepEqual(await slots(),[reordered[0],reordered[2],reordered[1],reordered[3]]);
    assert.equal(await page.locator('#hex-input').inputValue(),reordered[1]);
    await page.locator('[data-custom-color="2"]').press('Alt+ArrowLeft');
    assert.deepEqual(await slots(),reordered);
    console.log('PASS cancel, outside drop, normal click and keyboard swaps');
    await count(6);
    await edit(4,'#753951');await edit(5,'#FEB024');
    const six=await slots();
    await count(2);
    await page.reload();
    await page.locator('[data-page="custom"]').click();
    assert.equal((await slots()).length,2);
    await count(6);assert.deepEqual(await slots(),six);
    await count(3);await page.locator('#load-more').click();
    await checkGallery(six.slice(0,3));
    await page.locator('#generate-button').click();
    await checkGallery(six.slice(0,3));
    console.log('PASS six-color memory survives reload; hidden colors excluded from batches');
    await page.locator('[data-custom-color="1"]').click();
    assert.ok(await page.locator('.related-swatch.is-base').count());
    assert.equal(await page.locator('.related-swatch.is-base').getAttribute('data-related'),six[1]);
    await page.locator('[data-relation="complement"]').click();
    const related=page.locator('.related-swatch:not(.is-base)').first();
    const chosen=await related.getAttribute('data-related');await related.click();
    const expected=[six[0],chosen,six[2]];
    assert.deepEqual(await slots(),expected);await checkGallery(expected);
    await page.locator('[data-page="explore"]').click();
    assert.equal(await page.locator('#hex-input').inputValue(),exploreBase);
    await page.locator('[data-page="custom"]').click();
    console.log('PASS related colors follow active slot and preserve Explore');
    await page.locator('[data-save="0"]').click();
    await page.reload();await page.locator('[data-page="favorites"]').click();
    assert.equal(await page.locator('.palette-card').count(),1);
    await page.locator('.card-art').click();
    assert.equal(await page.locator('.detail-color').count(),3);
    await page.locator('#palette-dialog .close-dialog').click();
    await page.locator('[data-page="custom"]').click();
    await page.locator('#export-button').click();await page.locator('[data-format="json"]').click();
    const exported=JSON.parse(await page.locator('#export-preview').textContent());
    for(const p of exported.palettes)assert.deepEqual([...p.colors].sort(),[...expected].sort());
    const downloadPromise=page.waitForEvent('download');await page.locator('#download-export').click();
    const download=await downloadPromise;await download.saveAs(path.join(screenshotDir,download.suggestedFilename()));
    await page.locator('#export-dialog .close-dialog').click();
    await page.locator('[data-view="ui"]').click();
    await noOverflow();await page.screenshot({path:path.join(screenshotDir,'custom-desktop.png')});
    await page.locator('#theme-button').click();
    await page.screenshot({path:path.join(screenshotDir,'custom-dark.png')});
    await page.setViewportSize({width:390,height:1000});
    const heading=await page.locator('.custom-heading').boundingBox();
    assert.ok(heading.height<60,'Mobile editing hint should fit in two lines');
    await noOverflow();await page.screenshot({path:path.join(screenshotDir,'custom-mobile.png')});
    assert.ok(await page.locator('.related-colors').isVisible());
    await count(6);
    const mobileBefore=await slots();
    await page.locator('#custom-colors').scrollIntoViewIfNeeded();
    const touchFrom=await center(0),touchTo=await center(5);
    const session=await page.context().newCDPSession(page);
    await session.send('Emulation.setTouchEmulationEnabled',{enabled:true});
    await session.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{...touchFrom,id:1}]});
    await session.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{...touchTo,id:1}]});
    await page.screenshot({path:path.join(screenshotDir,'custom-touch-drag.png')});
    await session.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
    const mobileAfter=[...mobileBefore];[mobileAfter[0],mobileAfter[5]]=[mobileAfter[5],mobileAfter[0]];
    assert.deepEqual(await slots(),mobileAfter);
    assert.equal(await page.locator('#hex-input').inputValue(),mobileBefore[0]);
    assert.equal(await page.locator('[data-custom-color="5"]').getAttribute('aria-pressed'),'true');
    await checkGallery(mobileAfter);
    await count(2);await count(6);assert.deepEqual(await slots(),mobileAfter);
    await noOverflow();
    await page.screenshot({path:path.join(screenshotDir,'custom-touch-reordered.png')});
    console.log('PASS touch drag across rows preserves all six colors and count memory');
    assert.deepEqual(errors,[]);
    console.log('PASS favorites, details, download, dark/mobile layout; 0 browser errors');
  } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1;});
